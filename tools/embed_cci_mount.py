# Writes a C source file holding the bytes of mount.xex, so the launcher can
# carry the driver inside its own image. Run from the Launcher PreBuildEvent.
#   python embed_cci_mount.py <mount.xex> <output.c>
import sys

src, dst = sys.argv[1], sys.argv[2]
data = open(src, 'rb').read()

lines = []
for i in range(0, len(data), 16):
    lines.append('\t' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',')

with open(dst, 'w', newline='\n') as f:
    f.write('/* Generated by tools/embed_cci_mount.py. Do not edit. */\n')
    f.write('#include <xtl.h>\n\n')
    f.write('const BYTE g_CciMountImage[] = {\n')
    f.write('\n'.join(lines) + '\n')
    f.write('};\n')
    f.write('const DWORD g_CciMountImageSize = %d;\n' % len(data))
