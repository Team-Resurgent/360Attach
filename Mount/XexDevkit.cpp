{
	DWORD infoSize = ReadBE32( imageInfo + XEX_INFO_SIZE_FIELD );
	DWORD flags = ReadBE32( imageInfo + XEX_IMAGE_FLAGS_FIELD );
	BYTE hash[XECRYPT_SHA_DIGEST_SIZE];
	BYTE * salt = (flags & IMAGEFLAG_REVOCATION_CHECK_REQ) ? g_SaltRev : g_SaltXex;

	XeCryptRotSumSha( imageInfo + XEX_SIG_SIZE, infoSize - XEX_SIG_SIZE, NULL, 0, hash, sizeof(hash) );
	return XeCryptBnQwBeSigVerify( (PXECRYPT_SIG)imageInfo, hash, salt, (PXECRYPT_RSA)g_DebugPub );
}

static BOOL SignDebug( BYTE * imageInfo )
{
	DWORD infoSize = ReadBE32( imageInfo + XEX_INFO_SIZE_FIELD );
	DWORD flags = ReadBE32( imageInfo + XEX_IMAGE_FLAGS_FIELD );
	BYTE hash[XECRYPT_SHA_DIGEST_SIZE];
	BYTE * salt = (flags & IMAGEFLAG_REVOCATION_CHECK_REQ) ? g_SaltRev : g_SaltXex;

	XeCryptRotSumSha( imageInfo + XEX_SIG_SIZE, infoSize - XEX_SIG_SIZE, NULL, 0, hash, sizeof(hash) );
	if( !XeCryptBnQwBeSigCreate( (PXECRYPT_SIG)imageInfo, hash, salt, (PXECRYPT_RSA)g_DebugPub ) )
		return FALSE;
	return XeCryptBnQwNeModExp( (PQWORD)imageInfo, (PQWORD)imageInfo,
		(PQWORD)(g_DebugPrv + XEX_RSA_PRIV_EXP), (PQWORD)(g_DebugPrv + XEX_RSA_MODULUS), XEX_RSA_CQW );
}

BOOL XexDevkitIsConsoleDevkit( VOID )
{
	DWORD type = 0xFFFFFFFF;
	NTSTATUS status = XeKeysGetConsoleType( &type );
	LOG( "console type 0x%08X (status 0x%08X)", type, status );
	return NT_SUCCESS(status) && type == XEKEY_CONSOLETYPE_DEVKIT;
}

VOID XexDevkitClear( VOID )
{
	g_Patch.Active = FALSE;
	g_Patch.StartSector = 0;
	g_Patch.SectorCount = 0;
}

NTSTATUS XexDevkitPatch( DWORD imageLba, DWORD partitionSector, DWORD fileBytes )
{
	XexDevkitClear();
	EnsureKeys();

	if( fileBytes < XEX_SECURITY_OFFSET + sizeof(DWORD) )
	{
		LOG( "devkit: default.xex is too small to be an XEX" );
		return STATUS_FILE_CORRUPT_ERROR;
	}

	DWORD fileSectors = (fileBytes + CCI_SECTOR_SIZE - 1) / CCI_SECTOR_SIZE;
	DWORD sectors = fileSectors < XEX_PATCH_SECTORS ? fileSectors : XEX_PATCH_SECTORS;
	if( sectors == 0 ) return STATUS_FILE_CORRUPT_ERROR;

	NTSTATUS status = CciStreamReadSectors( imageLba, sectors, g_Patch.Data );
	if( !NT_SUCCESS(status) )
	{
		LOG( "devkit: reading default.xex header failed 0x%08X", status );
		return status;
	}

	if( memcmp( g_Patch.Data, "XEX2", 4 ) != 0 )
	{
		LOG( "devkit: default.xex is not an XEX2 file" );
		return STATUS_FILE_CORRUPT_ERROR;
	}

	DWORD bytesRead = sectors * CCI_SECTOR_SIZE;
	DWORD secOff = ReadBE32( g_Patch.Data + XEX_SECURITY_OFFSET );
	DWORD signedEnd = 0;
	DWORD infoSize = 0;
	BYTE * imageInfo = NULL;

	if( secOff >= XEX_SECURITY_OFFSET && secOff + XEX_IMAGE_INFO_OFFSET + XEX_IMAGE_KEY_END <= bytesRead )
	{
		imageInfo = g_Patch.Data + secOff + XEX_IMAGE_INFO_OFFSET;
		infoSize = ReadBE32( imageInfo + XEX_INFO_SIZE_FIELD );
		signedEnd = secOff + XEX_IMAGE_INFO_OFFSET + infoSize;
	}
	if( imageInfo == NULL || infoSize < XEX_IMAGE_KEY_END || signedEnd > bytesRead )
	{
		LOG( "devkit: default.xex image key is outside the %u-byte header buffer", bytesRead );
		return STATUS_FILE_CORRUPT_ERROR;
	}

	DWORD flags = ReadBE32( imageInfo + XEX_IMAGE_FLAGS_FIELD );
	if( flags & (IMAGEFLAG_MANUFACTURING_UTILITY | IMAGEFLAG_MANUFACTURING_TOOL) )
	{
		LOG( "devkit: manufacturing image, left unchanged" );
		return STATUS_SUCCESS;
	}
	if( VerifyDebugSign( imageInfo ) )
	{
		LOG( "devkit: default.xex is already signed for a devkit" );
		return STATUS_SUCCESS;
	}

	AesEcb( g_RetailKey, imageInfo + XEX_IMAGE_KEY_FIELD, FALSE );
	AesEcb( g_DebugKey, imageInfo + XEX_IMAGE_KEY_FIELD, TRUE );
	if( !SignDebug( imageInfo ) || !VerifyDebugSign( imageInfo ) )
	{
		LOG( "devkit: debug signature failed" );
		return STATUS_UNSUCCESSFUL;
	}

	// Sectors from the start of the file through the last changed byte.
	DWORD keyEnd = secOff + XEX_IMAGE_INFO_OFFSET + XEX_IMAGE_KEY_END;
	g_Patch.SectorCount = (keyEnd + CCI_SECTOR_SIZE - 1) / CCI_SECTOR_SIZE;
	g_Patch.StartSector = partitionSector;
	g_Patch.Active = TRUE;
	LOG( "devkit: resigned default.xex (partition sector 0x%X, %u header sector%s)",
		partitionSector, g_Patch.SectorCount, g_Patch.SectorCount == 1 ? "" : "s" );
	return STATUS_SUCCESS;
}

VOID XexDevkitSplice( DWORD sector, DWORD length, BYTE * dest )
{
	if( !g_Patch.Active || length == 0 ) return;

	ULONGLONG readStart = (ULONGLONG)sector * CCI_SECTOR_SIZE;
	ULONGLONG readEnd = readStart + length;
	ULONGLONG fileStart = (ULONGLONG)g_Patch.StartSector * CCI_SECTOR_SIZE;
	ULONGLONG fileEnd = fileStart + (ULONGLONG)g_Patch.SectorCount * CCI_SECTOR_SIZE;
	ULONGLONG lo = readStart > fileStart ? readStart : fileStart;
	ULONGLONG hi = readEnd < fileEnd ? readEnd : fileEnd;
	if( lo >= hi ) return;

	memcpy( dest + (DWORD)(lo - readStart), g_Patch.Data + (DWORD)(lo - fileStart), (DWORD)(hi - lo) );
}
