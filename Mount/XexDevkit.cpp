static DWORD ReadBE32( const BYTE * p )
{
	return ((DWORD)p[0] << 24) | ((DWORD)p[1] << 16) | ((DWORD)p[2] << 8) | (DWORD)p[3];
}

static VOID PrepareKey( BYTE * data, DWORD size )
{
	BYTE xorVal = 0xFF;
	for( DWORD i = 0; i < size; i++ )
		data[i] ^= xorVal--;
}

static VOID EnsureKeys( VOID )
{
	if( g_KeysReady ) return;
	memcpy( g_RetailKey, g_RetailKeyObf, sizeof(g_RetailKey) );
	memcpy( g_DebugKey, g_DebugKeyObf, sizeof(g_DebugKey) );
	memcpy( g_SaltXex, g_SaltXexObf, sizeof(g_SaltXex) );
	memcpy( g_SaltRev, g_SaltRevObf, sizeof(g_SaltRev) );
	memcpy( g_DebugPub, g_DebugPubObf, sizeof(g_DebugPub) );
	memcpy( g_DebugPrv, g_DebugPrvObf, sizeof(g_DebugPrv) );
	PrepareKey( g_RetailKey, sizeof(g_RetailKey) );
	PrepareKey( g_DebugKey, sizeof(g_DebugKey) );
	PrepareKey( g_SaltXex, sizeof(g_SaltXex) );
	PrepareKey( g_SaltRev, sizeof(g_SaltRev) );
	PrepareKey( g_DebugPub, sizeof(g_DebugPub) );
	PrepareKey( g_DebugPrv, sizeof(g_DebugPrv) );
	g_KeysReady = TRUE;
}

static VOID AesEcb( const BYTE * key, BYTE * block, BOOL encrypt )
{
	XECRYPT_AES_STATE state;
	XeCryptAesKey( &state, (PBYTE)key );
	XeCryptAesEcb( &state, block, block, encrypt );
}

